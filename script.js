function iniciarJogo() {

    jogador =
        nomeJogador.value.trim();


    if (!jogador) {

        alert(
            "Digite seu nome para continuar!"
        );

        nomeJogador.focus();

        return;

    }


    modalNome.classList.add(
        "oculto"
    );

    telaInicial.classList.add(
        "oculto"
    );

    resultado.style.display =
        "none";

    jogo.classList.remove(
        "oculto"
    );


    perguntaAtual = 0;

    acertos = 0;

    erros = 0;

    pontos = 0;

    // ==========================================
    // EMBARALHA AS PERGUNTAS
    // ==========================================

    perguntasDoJogo =
        embaralhar(bancoPerguntas);

    carregarPergunta();



    // ==========================================
    // ESCOLHE 20 PERGUNTAS DO BANCO
    // ==========================================

    perguntasDoJogo =
        embaralhar(
            bancoPerguntas
        ).slice(0, 20);


    // ==========================================
    // INICIA A PARTIDA
    // ==========================================

    carregarPergunta();

}


/* ==========================================
   CARREGAR PERGUNTA
========================================== */

function carregarPergunta() {

    clearInterval(
        intervalo
    );


    const pergunta =
        perguntasDoJogo[
        perguntaAtual
        ];


    imagem.src =
        pergunta.imagem;


    numero.textContent =
        perguntaAtual + 1;


    pontosElemento.textContent =
        pontos;


    progresso.style.width =
        (
            (perguntaAtual + 1) /
            perguntasDoJogo.length *
            100
        ) + "%";


    feedback.textContent =
        "";


    alternativas.innerHTML =
        "";

    // ========================================== 
    // ALTERNATIVAS EM ORDEM ALEATÓRIA 
    // ==========================================

    embaralhar(
        pergunta.alternativas
    ).forEach(
        opcao => {

            const botao =
                document.createElement(
                    "button"
                );


            botao.className =
                "alternativa";


            botao.textContent =
                opcao;


            botao.addEventListener(
                "click",
                function () {

                    verificarResposta(
                        botao,
                        opcao
                    );

                }
            );


            alternativas
                .appendChild(
                    botao
                );

        }
    );


    iniciarTimer();

}


/* ==========================================
   CRONÔMETRO
========================================== */

function iniciarTimer() {

    tempo = 20;

    timer.textContent =
        tempo;

    timer.classList.remove(
        "urgente"
    );


    intervalo =
        setInterval(
            function () {

                tempo--;

                timer.textContent =
                    tempo;


                if (tempo <= 5) {

                    timer
                        .classList
                        .add(
                            "urgente"
                        );

                }


                if (tempo <= 0) {

                    clearInterval(
                        intervalo
                    );

                    tempoEsgotado();

                }

            },
            1000
        );

}


/* ==========================================
   ÁUDIO
========================================== */

const audioContext =
    new (
        window.AudioContext ||
        window.webkitAudioContext
    )();


function tocarSom(tipo) {

    const oscillator =
        audioContext
            .createOscillator();


    const gain =
        audioContext
            .createGain();


    oscillator.connect(gain);

    gain.connect(
        audioContext.destination
    );


    if (tipo === "acerto") {

        oscillator.frequency.value =
            700;

        gain.gain.value =
            0.20;

        oscillator.start();

        oscillator
            .frequency
            .exponentialRampToValueAtTime(
                1000,
                audioContext.currentTime +
                0.30
            );

        oscillator.stop(
            audioContext.currentTime +
            0.3
        );

    }


    if (tipo === "erro") {

        oscillator.frequency.value =
            180;

        gain.gain.value =
            0.30;

        oscillator.start();

        oscillator
            .frequency
            .exponentialRampToValueAtTime(
                80,
                audioContext.currentTime +
                0.25
            );

        oscillator.stop(
            audioContext.currentTime +
            0.3
        );

    }


    if (tipo === "fim") {

        oscillator.frequency.value =
            100;

        gain.gain.value =
            0.15;

        oscillator.start();

        oscillator.stop(
            audioContext.currentTime +
            0.4
        );

    }

}


/* ==========================================
   VERIFICAR RESPOSTA
========================================== */

function verificarResposta(
    botao,
    resposta
) {

    clearInterval(
        intervalo
    );


    const pergunta =
        perguntasDoJogo[
        perguntaAtual
        ];


    const botoes =
        document.querySelectorAll(
            ".alternativa"
        );


    botoes.forEach(
        btn => {

            btn.disabled =
                true;

        }
    );


    if (
        resposta ===
        pergunta.resposta
    ) {

        botao
            .classList
            .add(
                "correta"
            );


        acertos++;


        const bonus =
            tempo * 10;


        const pontosGanhos =
            100 + bonus;


        pontos +=
            pontosGanhos;


        tocarSom(
            "acerto"
        );


        feedback.textContent =
            "🎉 ACERTOU! +" +
            pontosGanhos +
            " pontos";


        feedback.style.color =
            "#16c784";

    }

    else {

        botao
            .classList
            .add(
                "errada"
            );


        erros++;


        tocarSom(
            "erro"
        );


        feedback.textContent =
            "❌ ERROU!";


        feedback.style.color =
            "#ff3d57";


        botoes.forEach(
            btn => {

                if (
                    btn.textContent ===
                    pergunta.resposta
                ) {

                    btn.classList.add(
                        "correta"
                    );

                }

            }
        );

    }


    pontosElemento.textContent =
        pontos;


    setTimeout(
        proximaPergunta,
        1200
    );

}


/* ==========================================
   TEMPO ESGOTADO
========================================== */

function tempoEsgotado() {

    tocarSom(
        "fim"
    );


    const pergunta =
        perguntasDoJogo[
        perguntaAtual
        ];


    const botoes =
        document.querySelectorAll(
            ".alternativa"
        );


    botoes.forEach(
        botao => {

            botao.disabled =
                true;


            if (
                botao.textContent ===
                pergunta.resposta
            ) {

                botao.classList.add(
                    "correta"
                );

            }

        }
    );


    erros++;


    feedback.textContent =
        "⏰ Tempo esgotado!";


    feedback.style.color =
        "#ffb347";


    setTimeout(
        proximaPergunta,
        1200
    );

}


/* ==========================================
   PRÓXIMA PERGUNTA
========================================== */

function proximaPergunta() {

    perguntaAtual++;


    if (
        perguntaAtual <
        perguntasDoJogo.length
    ) {

        carregarPergunta();

    }

    else {

        finalizarJogo();

    }

}


/* ==========================================
   FINALIZAR JOGO
========================================== */


function finalizarJogo() {

    clearInterval(intervalo);

    // Conta a partida que acabou
    partidasCompletas++;

    /*
        A Fase Surpresa aparece
        a cada 2 partidas.

        Exemplos:
        2 % 2 = 0 → surpresa
        4 % 2 = 0 → surpresa
        6 % 2 = 0 → surpresa
        8 % 2 = 0 → surpresa
    */

    if (partidasCompletas % 1 === 0) {

        mostrarFaseSurpresa();

        return;
    }

    // Caso ainda não seja a hora da surpresa
    mostrarResultado();
}



