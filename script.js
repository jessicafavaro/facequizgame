/* ==========================================
   SALVAR RANKING
========================================== */

function salvarRanking() {

    let ranking =
        JSON.parse(
            localStorage.getItem(
                "faceQuizRanking"
            )
        ) || [];


    ranking.push({

        nome:
            jogador,

        pontos:
            pontos

    });


    ranking.sort(
        (a, b) =>
            b.pontos -
            a.pontos
    );


    ranking =
        ranking.slice(
            0,
            10
        );


    localStorage.setItem(
        "faceQuizRanking",
        JSON.stringify(
            ranking
        )
    );

}


