function iniciarFaseSurpresa() {

    faseSurpresa.classList.add("oculto");
    jogoSurpresa.classList.remove("oculto");

    surpresaRespondida = false;

    pontosSurpresa.textContent = pontos;
    feedbackSurpresa.textContent = "";
    alternativasSurpresa.innerHTML = "";

    // CARREGA E INICIA O VÍDEO

    const video = document.getElementById("videoSurpresa");

    video.src = "videos/fase-surpresa.mp4";
    video.load();

    video.currentTime = 0;

    video.play().catch(erro => {
        console.log(
            "O navegador bloqueou a reprodução automática com som. Clique em reproduzir no vídeo.",
            erro
        );
    });

    // CRIA AS ALTERNATIVAS JÁ CADASTRADAS
    perguntaSurpresa.alternativas.forEach(opcao => {

        const botao = document.createElement("button");

        botao.className = "alternativa";
        botao.textContent = opcao;

        botao.addEventListener("click", function () {
            responderSurpresa(botao, opcao);
        });

        alternativasSurpresa.appendChild(botao);

    });

    // INICIA O CRONÔMETRO
    iniciarTimerSurpresa();
}


function iniciarTimerSurpresa() {

    clearInterval(
        intervaloSurpresa
    );


    tempoSurpresa = 20;


    timerSurpresa.textContent =
        tempoSurpresa;


    timerSurpresa
        .classList
        .remove(
            "urgente"
        );


    intervaloSurpresa =
        setInterval(
            function () {

                tempoSurpresa--;


                timerSurpresa
                    .textContent =
                    tempoSurpresa;


                if (
                    tempoSurpresa <= 5
                ) {

                    timerSurpresa
                        .classList
                        .add(
                            "urgente"
                        );

                }


                if (
                    tempoSurpresa <= 0
                ) {

                    clearInterval(
                        intervaloSurpresa
                    );


                    surpresaTempoEsgotado();

                }

            },
            1000
        );

}


/* ==========================================
  VERIFICAR RESPOSTA FASE SURPRESA
========================================== */


function responderSurpresa(
    botao,
    resposta
) {

    if (surpresaRespondida) {

        return;

    }


    surpresaRespondida =
        true;


    clearInterval(
        intervaloSurpresa
    );

    pararVideoSurpresa();


    const botoes =
        document.querySelectorAll(
            "#alternativasSurpresa .alternativa"
        );


    botoes.forEach(
        btn => {

            btn.disabled =
                true;

        }
    );


    if (
        resposta ===
        perguntaSurpresa.resposta
    ) {

        /*
            BÔNUS DA FASE SURPRESA
        */

        pontos += 500;


        acertos++;


        botao
            .classList
            .add(
                "correta"
            );


        tocarSom(
            "acerto"
        );


        feedbackSurpresa.textContent =
            "O NOVO INTEGRANTE DA FAMILIA ";


        feedbackSurpresa.style.color =
            "#ffd700";


        pontosSurpresa.textContent =
            pontos;

    }

    else {

        erros++;


        botao
            .classList
            .add(
                "errada"
            );


        tocarSom(
            "erro"
        );


        feedbackSurpresa.textContent =
            "O NOVO INTEGRANTE DA FAMILIA";


        feedbackSurpresa.style.color =
            "#ff3d57";


        mostrarRespostaSurpresa(
            botoes
        );

    }


    setTimeout(
        finalizarSurpresa,
        1500
    );

}

function mostrarRespostaSurpresa(
    botoes
) {

    botoes.forEach(
        botao => {

            if (
                botao.textContent ===
                perguntaSurpresa.resposta
            ) {

                botao
                    .classList
                    .add(
                        "correta"
                    );

            }

        }
    );

}

function surpresaTempoEsgotado() {

    if (surpresaRespondida) {

        return;

    }


    surpresaRespondida =
        true;

    pararVideoSurpresa();    

    erros++;


    tocarSom(
        "fim"
    );


    const botoes =
        document.querySelectorAll(
            "#alternativasSurpresa .alternativa"
        );


    botoes.forEach(
        botao => {

            botao.disabled =
                true;

        }
    );


    mostrarRespostaSurpresa(
        botoes
    );


    feedbackSurpresa.textContent =
        "⏰ Tempo esgotado!";


    feedbackSurpresa.style.color =
        "#ffb347";


    setTimeout(
        finalizarSurpresa,
        1500
    );

}

function finalizarSurpresa() {

    clearInterval(
        intervaloSurpresa
    );

    pararVideoSurpresa();

    jogoSurpresa
        .classList
        .add("oculto");


    /*
        Depois da Fase Surpresa,
        finalmente mostra o resultado.
    */

    mostrarResultado();

}


