// ==========================================
// CARREGAR RANKING NA TELA
// ==========================================

function carregarRankingTela() {

    const ranking =
        JSON.parse(
            localStorage.getItem(
                "faceQuizRanking"
            )
        ) || [];


    podioRanking.innerHTML =
        "";

    listaRankingTela.innerHTML =
        "";


    // ==========================================
    // RANKING VAZIO
    // ==========================================

    if (ranking.length === 0) {

        listaRankingTela.innerHTML = `

            <div class="ranking-vazio">

                <div class="icone">
                    🏆
                </div>

                <h3>
                    Ainda não existem jogadores!
                </h3>

                <p>
                    Seja o primeiro a entrar
                    para o ranking.
                </p>

            </div>

        `;

        return;

    }


    // ==========================================
    // TOP 3
    // ==========================================

    const top3 =
        ranking.slice(0, 3);


    top3.forEach(
        (jogador, index) => {

            let medalha;

            let classe;


            if (index === 0) {

                medalha = "🥇";

                classe = "primeiro";

            }

            else if (index === 1) {

                medalha = "🥈";

                classe = "segundo";

            }

            else {

                medalha = "🥉";

                classe = "terceiro";

            }


            podioRanking.innerHTML += `

                <div
                    class="podio-item ${classe}">

                    <div
                        class="podio-medalha">

                        ${medalha}

                    </div>

                    <div
                        class="podio-nome">

                        ${jogador.nome}

                    </div>

                    <div
                        class="podio-pontos">

                        ${jogador.pontos} pts

                    </div>

                </div>

            `;

        }
    );


    // ==========================================
    // POSIÇÕES 4 ATÉ 10
    // ==========================================

    ranking
        .slice(3, 10)
        .forEach(
            (jogador, index) => {

                const posicao =
                    index + 4;


                listaRankingTela.innerHTML += `

                    <div
                        class="ranking-tela-item">

                        <span
                            class="ranking-posicao">

                            ${posicao}º

                        </span>


                        <span
                            class="ranking-nome">

                            ${jogador.nome}

                        </span>


                        <span
                            class="ranking-pontos">

                            ${jogador.pontos} pts

                        </span>

                    </div>

                `;

            }
        );

}


