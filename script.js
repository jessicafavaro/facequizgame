// ==========================================
// EMBARALHAR ARRAY
// ==========================================

function embaralhar(bancoPerguntas) {

    const copia = [...bancoPerguntas];

    for (
        let i = copia.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() * (i + 1)
            );

        [
            copia[i],
            copia[j]
        ] = [
                copia[j],
                copia[i]
            ];

    }

    return copia;
}



